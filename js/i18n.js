/* Langue du site : anglais par défaut, français au choix (bouton EN / FR, gardé dans le navigateur).
   Les textes sont écrits en anglais dans le code : t('…') ; FR donne leur traduction, {x} = valeur insérée.
   Une phrase sans entrée dans FR reste en anglais. Chargé avant tous les autres scripts. */
const LANG = (() => { try { return localStorage.getItem('lang') === 'fr' ? 'fr' : 'en' } catch { return 'en' } })()
const LOCALE = LANG === 'fr' ? 'fr-FR' : 'en-GB'
document.documentElement.lang = LANG

function t(s, vars) {
  let out = LANG === 'fr' && FR[s] != null ? FR[s] : s
  if (vars) out = out.replace(/\{(\w+)\}/g, (m, k) => vars[k] ?? m)
  return out
}
const tr = t  // là où « t » désigne déjà un titre
/* Singulier / pluriel : tn(3, '{n} track', '{n} tracks') */
const tn = (n, one, many, vars = {}) => t(n === 1 ? one : many, { n, ...vars })
const listAnd = a => a.length < 2 ? a.join('') : `${a.slice(0, -1).join(', ')} ${t('and')} ${a.at(-1)}`
function setLang(l) {
  try { localStorage.setItem('lang', l) } catch {}
  location.reload()
}
/* Textes écrits dans le HTML : data-t (texte seul), data-t-html (avec balises), placeholder, aria-label, title */
function translatePage(root = document) {
  if (LANG !== 'fr') return
  root.querySelectorAll('[data-t]').forEach(e => e.textContent = t(e.textContent.trim()))
  root.querySelectorAll('[data-t-html]').forEach(e => e.innerHTML = t(e.innerHTML.trim()))
  root.querySelectorAll('[placeholder]').forEach(e => e.placeholder = t(e.placeholder))
  root.querySelectorAll('[aria-label]').forEach(e => e.setAttribute('aria-label', t(e.getAttribute('aria-label'))))
  root.querySelectorAll('[data-t-title]').forEach(e => e.title = t(e.title))
  document.title = t(document.title)
}

